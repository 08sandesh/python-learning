s1 ={'mango' , 58 , 'grapes' , True , 90 , False}

s1.add('Moon')     #  adds the value
print(s1)

print(len(s1))     #  gives the length of the set

s1.remove(True)    #  removes the value
print(s1)

s1.pop()           #  removes a random value
print(s1)

s1.clear()         #  removes all values from set
print(s1)

