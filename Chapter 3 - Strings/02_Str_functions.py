a = 'sandesh'

print(len(a))  #  len gives the length of the strings

print(a.endswith('esh'))  #  endswith checks whether the variable string ends with 'esh' or not.

print(a.startswith('san'))  #  startswith checks whether the variable string starts with 'san' or not.

print(a.capitalize())  # makes the first letter to uppercase

print(a.index('e'))  # gives the index

print(a.count('s'))  # counts the occurence of s.

print(a.find('desh'))  # gives the index of first letter

print(a.replace('s','ss'))  # replace the word in the string

print(a.replace('p','i'))
print(a.count('z'))
