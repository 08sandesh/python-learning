#  Arithmetic Operators

a = 10
b = 2

print("a + b =",a + b)
print("a - b =",a - b)
print("a * b =",a * b)
print("a // b =",a // b)  # Divide operator returns quetionent 
print("a % b =",a % b)  # Modulo operator returns remainder

#  Assignment Operators

print()
print("c = 45")

d = 11
d+=4        # First increment the value of d by 4 and then assign to d
print(d)

e = 11
e-=4        # First decrement the value of e by 4 and then assign to e
print(e)

